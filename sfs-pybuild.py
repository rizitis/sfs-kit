#!/usr/bin/env python3
# sfs-pybuild.py - read [build-system] requires from the pyproject.toml of
# every python source tarball in the tree and write them as manual.tsv
# lines (data/pybuild.tsv).  gen.py reads that file next to manual.tsv.
#
# Why: "python3 -m build --no-isolation" refuses to start when a build
# requirement is missing (pluggy needs setuptools-scm, ...), and nothing
# else shows these: they are not runtime imports, the SlackBuild never
# names them.
#
#   sfs-pybuild.py --src $SLACKSRC --units plan/units.tsv --out data/pybuild.tsv
#
# Needs tar with lzip/xz/zstd support (any Slackware host) and python >= 3.11.

import argparse, os, re, subprocess, sys, tomllib

ap = argparse.ArgumentParser()
ap.add_argument('--src', required=True)
ap.add_argument('--units', required=True)
ap.add_argument('--out', required=True)
ap.add_argument('--tarball-map', help='unit<TAB>tarball lines instead of looking in --src')
args = ap.parse_args()

PYBUILD = re.compile(r'-m build\b|-m installer\b|flit_core\.wheel|setup\.py|pip3? install')
TARBALL = re.compile(r'\.(tar\.(gz|xz|lz|bz2|zst)|tgz|zip)$')

def norm(n):
    return re.sub(r'[-_.]+', '-', n).lower()

units = {}          # unit -> outputs
index = {}          # normalized name -> package
for line in open(args.units):
    p = line.rstrip('\n').split('\t')
    if p[0] == 'unit' or len(p) < 4:
        continue
    outs = p[3].split()
    units[p[0]] = outs
    for o in outs:
        index.setdefault(norm(o), o)
        if o.lower().startswith('python-'):
            index.setdefault(norm(o[7:]), o)
        if o.lower().startswith('python3-'):
            index.setdefault(norm(o[8:]), o)

def owner(unit):
    base = os.path.basename(unit.split(':')[0])
    outs = units.get(unit, [])
    return base if base in outs else (outs[0] if outs else base)

def pyproject(tarball):
    if tarball.endswith('.zip'):
        r = subprocess.run(['unzip', '-p', tarball, '*/pyproject.toml'], capture_output=True)
    else:
        r = subprocess.run(['tar', '--wildcards', '--no-wildcards-match-slash', '-xOf', tarball,
                            '*/pyproject.toml'], capture_output=True)
    return r.stdout.decode('utf-8', 'replace') if r.stdout else None

todo = []
if args.tarball_map:
    for line in open(args.tarball_map):
        u, t = line.rstrip('\n').split('\t')
        todo.append((u, t))
else:
    for u in sorted(units):
        if ':' in u:
            continue
        d = os.path.join(args.src, u)
        if not os.path.isdir(d):
            continue
        scripts = [f for f in os.listdir(d) if f.endswith('.SlackBuild')]
        # comments do not count: file.SlackBuild has its python part commented out
        def code(s):
            return '\n'.join(l for l in open(os.path.join(d, s), errors='replace')
                             if not l.lstrip().startswith('#'))
        if not any(PYBUILD.search(code(s)) for s in scripts):
            continue
        for f in sorted(os.listdir(d)):
            if TARBALL.search(f):
                todo.append((u, os.path.join(d, f)))

lines, unknown = {}, []
for u, t in todo:
    me = owner(u)
    text = pyproject(t)
    if text is None:
        reqs = ['setuptools', 'wheel'] if 'setup' in (subprocess.run(
            ['tar', '-tf', t], capture_output=True).stdout.decode(errors='replace')) else []
        why = 'no pyproject.toml, setup.py'
    else:
        try:
            reqs = tomllib.loads(text).get('build-system', {}).get('requires', [])
        except tomllib.TOMLDecodeError as e:
            print(f'{u}: bad pyproject.toml in {t}: {e}', file=sys.stderr)
            continue
        why = 'pyproject.toml'
    for r in reqs:
        # "setuptools-scm[toml]>=8", "cffi; platform_python_implementation != 'PyPy'"
        if ';' in r and re.search(r"python_version\s*<\s*['\"]3\.(\d|1[01])['\"]", r):
            continue          # only for old pythons
        name = re.match(r'\s*([A-Za-z0-9_.-]+)', r)
        if not name:
            continue
        pkg = index.get(norm(name.group(1)))
        if pkg is None:
            unknown.append(f'{u}: {r.strip()}')
            continue
        if pkg in units.get(u, []) or pkg == me:
            continue
        lines.setdefault((me, pkg), f'{me}\t{pkg}\t3\t# {why}: {r.strip()}')

with open(args.out, 'w') as f:
    f.write('# generated by sfs-pybuild.py: [build-system] requires of the python\n')
    f.write('# tarballs, in manual.tsv format.  Do not edit; fix manual.tsv instead.\n')
    for k in sorted(lines):
        f.write(lines[k] + '\n')
print(f'{len(todo)} tarballs, {len(lines)} build requirements -> {args.out}')
for x in unknown:
    print('  not in the tree:', x)
